import assert from 'node:assert/strict'

// Run against the bundled fixtures/resident-dialogue.tsx in a fresh browser context.
export async function testResidentDialogue(page, url) {
  await page.goto(url)
  const choice = name => page.getByRole('button', { name, exact: true })
  const reopen = async () => {
    const world = page.frames().find(frame => new URL(frame.url()).pathname.startsWith('/world/'))
    await world.evaluate(origin => parent.postMessage({ source: 'agent-isles-world', version: 1, type: 'resident:selected', payload: { residentId: 'coordinator' } }, origin), new URL(url).origin)
    await choice('选择文件夹').waitFor()
  }
  await choice('选择文件夹').waitFor()
  assert.equal(await page.locator('#town-folder').count(), 0)
  assert.equal(await page.getByText('模型设置', { exact: true }).count(), 0)
  await page.evaluate(() => { window.dialogueTest.pick = 'cancel' })
  await choice('选择文件夹').click()
  await page.waitForFunction(() => !document.querySelector('.town-primary').disabled)
  assert.deepEqual(await page.evaluate(() => window.dialogueTest.calls), [])
  await page.evaluate(() => { window.dialogueTest.pick = 'fail' })
  await choice('选择文件夹').click()
  await page.getByRole('alert').filter({ hasText: '文件夹暂时无法打开' }).waitFor()
  await choice('关闭居民面板').click()
  assert.equal(await page.locator('.town-conversation').count(), 0)
  await reopen()
  await page.evaluate(() => { window.dialogueTest.pick = 'pending' })
  await choice('选择文件夹').click()
  await page.waitForFunction(() => !!window.dialogueTest.finish)
  await page.getByRole('status').filter({ hasText: '等待系统文件夹选择窗口' }).waitFor()
  await choice('取消选择').click()
  await page.waitForFunction(() => !document.querySelector('.town-primary').disabled)
  assert.equal(await page.evaluate(() => window.dialogueTest.aborted), true)
  await choice('选择文件夹').click()
  await choice('取消选择').waitFor()
  await choice('关闭居民面板').click()
  assert.equal(await page.evaluate(() => window.dialogueTest.aborted), true)
  await page.evaluate(() => window.dialogueTest.finish())
  assert.deepEqual(await page.evaluate(() => window.dialogueTest.calls), [])
  await reopen()
  await page.evaluate(() => { window.dialogueTest.pick = 'ok' })
  await choice('已有项目 / 输入路径').click()
  await choice('输入文件夹路径').click()
  await page.locator('#town-folder').fill('D:\\Projects\\Manual')
  await choice('安顿在这里').click()
  await choice('找芽芽聊聊').waitFor()
  assert.deepEqual(await page.evaluate(() => window.dialogueTest.calls), ['bind:D:\\Projects\\Manual'])
  await choice('认识其他居民').click()
  await choice('找苔伯学习项目').click()
  await page.getByText('你的问题', { exact: true }).waitFor()
  assert.ok((await page.evaluate(() => window.dialogueTest.calls)).includes('resident:teacher'))
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.town-conversation').count(), 0)
  await page.reload()
  await page.locator('iframe').waitFor()
  await page.getByText('上次项目已不在当前项目列表中，请选择已有项目或重新绑定。原会话不会被自动替换。').waitFor()
  assert.equal(await page.locator('.town-conversation').count(), 1, 'Missing restored project is explained instead of silently restarting onboarding')
  await page.evaluate(() => localStorage.clear())
  await page.reload()
  await choice('选择文件夹').waitFor()
  await page.evaluate(() => { window.dialogueTest.configured = false })
  await choice('还有件事…').click()
  await choice('模型设置').click()
  await choice('关闭模型设置').click()
  await choice('返回对话').click()
  await choice('选择文件夹').click()
  await choice('连接模型').waitFor()
  assert.equal(await choice('找芽芽聊聊').count(), 0)
  assert.ok((await page.evaluate(() => window.dialogueTest.calls)).includes('bind:D:\\Projects\\Test'))
  return { canceled: true, failureRecovery: true, dismissedPending: true, manualBinding: true, residentHandoff: true, returningUser: true, missingModel: true, nativeBinding: true, abortPicker: true }
}
